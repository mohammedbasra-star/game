# -*- coding: utf-8 -*-
"""
الدرس الثالث: الشروط واتخاذ القرارات البرمجية (If - Elif - Else)
================================================================
في هذا الدرس سنتعلم:
1. كيف نجعل الكمبيوتر يتخذ قرارات بناءً على شروط محددة
2. معاملات المقارنة (أكبر من > ، أصغر من < ، يساوي == ، لا يساوي !=)
3. الشروط المركبة باستخدام (and و or)
4. تطبيق عملي: نظام إنذار لمراقبة حرارة توربينة غازية
"""

import sys
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")
if hasattr(sys.stdin, "reconfigure"):
    sys.stdin.reconfigure(encoding="utf-8")

print("=" * 60)
print("     الدرس الثالث: الشروط واتخاذ القرارات في بايثون        ")
print("=" * 60)

# -------------------------------------------------------------
# 1. كيف يعمل الشرط (if / else)؟
# -------------------------------------------------------------
عمر = 18

if عمر >= 18:
    print(f"العمر {عمر}: مسموح لك بالحصول على رخصة القيادة.")
else:
    print(f"العمر {عمر}: غير مسموح لك، يجب أن تبلغ 18 عاماً.")

# -------------------------------------------------------------
# 2. الشروط المتعددة (elif)
# -------------------------------------------------------------
# elif تعني "وإلا إذا تحقق شرط آخر"
درجة_الطالب = 87

print(f"\nفحص تقدير الطالب لدرجة ({درجة_الطالب}):")
if درجة_الطالب >= 90:
    print("التقدير: ممتاز (A) 🌟")
elif درجة_الطالب >= 80:
    print("التقدير: جيد جداً (B) 👍")
elif درجة_الطالب >= 70:
    print("التقدير: جيد (C)")
elif درجة_الطالب >= 50:
    print("التقدير: مقبول (D)")
else:
    print("التقدير: راسب (F)")

# -------------------------------------------------------------
# 3. تطبيق هندسي تفاعلي: مراقبة درجة حرارة التوربينة (EGT)
# -------------------------------------------------------------
print("\n" + "-" * 60)
print("نظام حماية التوربينة من الحرارة الزائدة (SCADA Simulator):")
print("-" * 60)

حرارة_نص = input("أدخل درجة حرارة غازات العادم EGT بالمئوية (مثال: 580): ")

try:
    حرارة = float(حرارة_نص) if حرارة_نص.strip() else 580.0

    print(f"\nالقراءة المسجلة: {حرارة} °C")
    if حرارة > 650:
        print("🚨 [خطر شديد]: تجاوز الحد الأقصى! إيقاف اضطراري فوري (Emergency Trip)!")
    elif حرارة > 600:
        print("⚠️ [تحذير]: حرارة مرتفعة جداً! تشغيل نظام التبريد بأقصى طاقة.")
    elif حرارة >= 450 and حرارة <= 600:
        print("✅ [وضع طبيعي ومثالي]: التوربينة تعمل ضمن النطاق التصميمي الآمن.")
    else:
        print("ℹ️ [وضع الإحماء أو التوقف]: درجة الحرارة منخفضة.")
except ValueError:
    print("يرجى إدخال رقم صحيح للحرارة.")

print("\nممتاز جداً! أصبحت الآن تعرف كيف تبني منطق البرامج 🚀")
print("=" * 60)

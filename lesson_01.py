# -*- coding: utf-8 -*-
"""
الدرس الأول: مدخل إلى لغة بايثون - المتغيرات وأنواع البيانات الأساسية
=====================================================================
مرحباً بك في عالم البرمجة بلغة بايثون!
في هذا الدرس سنتعلم:
1. كيف تطبع نصاً على الشاشة باستخدام دالة print
2. ما هو "المتغير" (Variable) وكيف نخزن البيانات
3. أنواع البيانات الأساسية (نص، رقم صحيح، رقم عشري، قيمة منطقية)
4. كيف تستقبل مدخلات من المستخدم باستخدام دالة input
"""

import sys
# لضمان ظهور النصوص العربية بشكل سليم في شاشة الأوامر (Terminal) على ويندوز
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")
if hasattr(sys.stdin, "reconfigure"):
    sys.stdin.reconfigure(encoding="utf-8")

print("=" * 60)
print("       مرحباً بك في الدرس الأول من دورة تعلم بايثون       ")
print("=" * 60)

# -------------------------------------------------------------
# 1. طباعة النصوص (The print function)
# -------------------------------------------------------------
# دالة print تقوم بعرض أي شيء تضعه بين القوسين على الشاشة.
print("\n[1] طباعة النصوص:")
print("أهلاً بك في أول برنامج بايثون تكتبه بنفسك!")

# -------------------------------------------------------------
# 2. المتغيرات وأنواع البيانات (Variables & Data Types)
# -------------------------------------------------------------
# المتغير: هو عبارة عن صندوق في ذاكرة الكمبيوتر نضع له اسماً ونخزن فيه قيمة.
print("\n[2] المتغيرات وأنواع البيانات:")

# أ) نوع نصي (String): يوضع بين علامات تنصيص " "
اسم_الطالب = "محمد"

# ب) رقم صحيح (Integer): عدد بدون فواصل عشرية
العمر = 25

# ج) رقم عشري (Float): عدد يحتوي على فاصلة عشرية
درجة_الحرارة = 36.6

# د) قيمة منطقية (Boolean): إما صواب (True) أو خطأ (False)
يحب_البرمجة = True

# -------------------------------------------------------------
# 3. عرض المتغيرات باستخدام f-strings (طريقة بايثون الحديثة والذكية)
# -------------------------------------------------------------
# نضع حرف f قبل علامة التنصيص، ونضع اسم المتغير داخل أقواس معقوفة { }
print(f"الاسم المسجل: {اسم_الطالب}")
print(f"العمر: {العمر} سنة")
print(f"درجة الحرارة: {درجة_الحرارة} درجة مئوية")
print(f"هل يحب البرمجة؟ الإجابة: {يحب_البرمجة}")

# -------------------------------------------------------------
# 4. معرفة نوع المتغير (type)
# -------------------------------------------------------------
print("\n[3] معرفة نوع كل متغير:")
print(f"نوع المتغير (اسم_الطالب): {type(اسم_الطالب).__name__}")
print(f"نوع المتغير (العمر): {type(العمر).__name__}")
print(f"نوع المتغير (درجة_الحرارة): {type(درجة_الحرارة).__name__}")

# -------------------------------------------------------------
# 5. تجربة تفاعلية: أدخل بياناتك بنفسك!
# -------------------------------------------------------------
print("\n" + "-" * 60)
print("تطبيق تفاعلي (أدخل بياناتك):")
print("-" * 60)

# دالة input تطلب من المستخدم كتابة نص من لوحة المفاتيح
اسمك = input("ما هو اسمك؟: ")
if not اسمك.strip():
    اسمك = "مبتكر بايثون"

print(f"\nسعداء بلقائك يا {اسمك}! لقد أكملت الدرس الأول بنجاح 🎉")
print("=" * 60)

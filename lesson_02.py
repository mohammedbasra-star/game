# -*- coding: utf-8 -*-
"""
الدرس الثاني: العمليات الحسابية وتحويل أنواع البيانات
=====================================================
في هذا الدرس سنتعلم:
1. العمليات الحسابية في بايثون (+ , - , * , / , // , % , **)
2. أسبقية العمليات الرياضية (الأقواس أولاً ثم الضرب والقسمة...)
3. تحويل النصوص إلى أرقام (int و float)
4. تطبيق عملي: آلة حاسبة هندسية مبسطة
"""

import sys
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")
if hasattr(sys.stdin, "reconfigure"):
    sys.stdin.reconfigure(encoding="utf-8")

print("=" * 60)
print("     الدرس الثاني: العمليات الحسابية وتحويل البيانات       ")
print("=" * 60)

# -------------------------------------------------------------
# 1. العمليات الحسابية الأساسية
# -------------------------------------------------------------
س = 10
ص = 3

print(f"القيم المبدئية: س = {س} ، ص = {ص}\n")
print(f"الجمع (س + ص):           {س + ص}")
print(f"الطرح (س - ص):           {س - ص}")
print(f"الضرب (س * ص):           {س * ص}")
print(f"القسمة العادية (س / ص):   {س / ص:.2f}")       # ناتج عشري (Float)
print(f"القسمة الصحيحة (س // ص): {س // ص}")         # تحذف الفواصل
print(f"باقي القسمة (س % ص):      {س % ص}")          # مفيد لمعرفة الأعداد الزوجية والفردية
print(f"الأس (س ** ص):           {س ** ص}")         # 10 أس 3 = 1000

# -------------------------------------------------------------
# 2. تحويل أنواع البيانات (Type Casting)
# -------------------------------------------------------------
# ملاحظة مهمة جداً: أي قيمة تأتي من دالة input تكون دائماً نصاً (String)
# إذا أردت إجراء عمليات حسابية عليها، يجب تحويلها إلى رقم int أو float
print("\n" + "-" * 60)
print("تحويل النصوص إلى أرقام:")
print("-" * 60)

نص_رقم = "50"
الرقم_الحقيقي = int(نص_رقم)  # تحويل إلى رقم صحيح
النتيجة = الرقم_الحقيقي + 20
print(f"جمع الرقم بعد تحويله: {الرقم_الحقيقي} + 20 = {النتيجة}")

# -------------------------------------------------------------
# 3. تطبيق عملي تفاعلي: حساب مساحة مستطيل
# -------------------------------------------------------------
print("\n" + "-" * 60)
print("تطبيق هندسي: حساب مساحة غرفة أو قطعة أرض (مستطيل):")
print("-" * 60)

try:
    الطول_نص = input("أدخل الطول بالمتر (مثال 5.5): ")
    العرض_نص = input("أدخل العرض بالمتر (مثال 3.0): ")

    # تحويل المدخلات إلى أرقام عشرية
    الطول = float(الطول_نص) if الطول_نص.strip() else 5.0
    العرض = float(العرض_نص) if العرض_نص.strip() else 3.0

    المساحة = الطول * العرض
    المحيط = 2 * (الطول + العرض)

    print(f"\nالنتائج الهندسية:")
    print(f"- المساحة الإجمالية = {المساحة:.2f} متر مربع")
    print(f"- المحيط = {المحيط:.2f} متر")
except ValueError:
    print("تنبيه: يجب إدخال أرقام صحيحة أو عشرية فقط!")

print("\nأحسنت! أكملت الدرس الثاني بنجاح 🎯")
print("=" * 60)
